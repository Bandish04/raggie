@pytest.mark.parametrize(
    ("license_", "category"),
    [
        ("MIT", g.PERMISSIVE),
        ("Apache-2.0 AND MIT", g.PERMISSIVE),
        ("BSD-3-Clause", g.PERMISSIVE),
        ("LGPL-3.0-or-later", g.WEAK_COPYLEFT),
        ("GNU Lesser General Public License v3 (LGPLv3)", g.WEAK_COPYLEFT),
        ("MPL-2.0", g.WEAK_COPYLEFT),
        ("GPL-3.0-only", g.COPYLEFT),
        ("AGPL-3.0", g.COPYLEFT),
        ("SSPL-1.0", g.COPYLEFT),
        ("BUSL-1.1", g.RESTRICTED),
        ("CC-BY-NC-4.0", g.RESTRICTED),
        ("CC-BY-4.0", g.PERMISSIVE),
        ("OFL-1.1", g.PERMISSIVE),
        # Dual licensing: the most permissive alternative applies.
        ("MIT OR GPL-2.0", g.PERMISSIVE),
        ("(MIT OR Apache-2.0) AND LGPL-3.0", g.WEAK_COPYLEFT),
        ("", g.UNKNOWN),
        ("UNKNOWN", g.UNKNOWN),
    ],
)
def test_classify(license_, category) -> None:
    assert g.classify(license_) == category


def test_parse_uv_export_skips_comments_editables_and_markers() -> None:
    text = (
        "# This file was autogenerated by uv\n"
        "anyio==4.14.2 ; python_full_version < '3.15'\n"
        "anyio==4.16.0 ; python_full_version >= '3.15'\n"
        "-e ../shared/example_lib\n"
        "fastapi==0.162.0\n"
        "uvicorn[standard]==0.32.0\n"
    )
    assert g.parse_uv_export(text) == [
        ("anyio", "4.14.2"),
        ("anyio", "4.16.0"),
        ("fastapi", "0.162.0"),
        ("uvicorn", "0.32.0"),
    ]


@pytest.mark.parametrize(
    ("info", "license_"),
    [
        ({"license_expression": "MIT", "license": "whatever"}, "MIT"),
        (
            {"license": "", "classifiers": ["License :: OSI Approved :: Apache Software License"]},
            "Apache-2.0",
        ),
        (
            {"license": "BSD-3-Clause", "classifiers": ["License :: OSI Approved :: BSD License"]},
            "BSD-3-Clause",
        ),
        # The full license text pasted into `license` is not a license name.
        (
            {
                "license": "Copyright (c) X\n\nPermission is hereby granted..." * 3,
                "classifiers": ["License :: OSI Approved :: MIT License"],
            },
            "MIT",
        ),
        ({"license": None, "classifiers": []}, ""),
        # A vague `license` falls back to the classifiers; several mean a choice.
        (
            {
                "license": "Dual License",
                "classifiers": [
                    "License :: OSI Approved :: BSD License",
                    "License :: OSI Approved :: Apache Software License",
                ],
            },
            "BSD OR Apache-2.0",
        ),
    ],
)
def test_pypi_license(info, license_) -> None:
    assert g.pypi_license(info) == license_


def test_verified_overrides_fill_missing_pypi_metadata() -> None:
    assert g.pypi_license({"license": None, "classifiers": []}, "py-rust-stemmers") == "MIT"
    # An override never replaces metadata PyPI does have.
    assert g.pypi_license({"license_expression": "BSD-3-Clause"}, "py-rust-stemmers") == (
        "BSD-3-Clause"
    )


def test_parse_go_report_takes_versions_from_go_list() -> None:
    report = (
        "github.com/cespare/xxhash/v2,https://github.com/cespare/xxhash/blob/v2.3.0/LICENSE.txt,MIT\n"
        "golang.org/x/text,https://cs.opensource.google/go/x/text/+/v0.20.0:LICENSE,BSD-3-Clause\n"
    )
    versions = {"github.com/cespare/xxhash/v2": "v2.3.0", "golang.org/x/text": "v0.20.0"}
    assert g.parse_go_report(report, versions) == [
        g.Dep(
            "github.com/cespare/xxhash/v2",
            "v2.3.0",
            "MIT",
            "https://github.com/cespare/xxhash/blob/v2.3.0/LICENSE.txt",
        ),
        g.Dep(
            "golang.org/x/text",
            "v0.20.0",
            "BSD-3-Clause",
            "https://cs.opensource.google/go/x/text/+/v0.20.0:LICENSE",
        ),
    ]


def test_parse_go_report_maps_subpackages_to_their_module() -> None:
    report = "golang.org/x/text/unicode/norm,https://x/LICENSE,BSD-3-Clause\n"
    versions = {"golang.org/x/text": "v0.20.0"}
    assert g.parse_go_report(report, versions)[0].version == "v0.20.0"


def test_parse_pnpm() -> None:
    data = {
        "MIT": [{"name": "react", "versions": ["19.0.0"], "homepage": "https://react.dev"}],
        "LGPL-3.0-or-later": [{"name": "@img/sharp-libvips-linux-x64", "versions": ["1.2.0"]}],
    }
    assert g.parse_pnpm(json.dumps(data)) == [
        g.Dep(
            "@img/sharp-libvips-linux-x64",
            "1.2.0",
            "LGPL-3.0-or-later",
            "https://www.npmjs.com/package/@img/sharp-libvips-linux-x64",
        ),
        g.Dep("react", "19.0.0", "MIT", "https://react.dev"),
    ]


def test_license_from_text() -> None:
    assert g.license_from_text("SIL OPEN FONT LICENSE Version 1.1 - 26 February 2007") == "OFL-1.1"
    assert g.license_from_text("                Apache License\n  Version 2.0, January") == (
        "Apache-2.0"
    )
    assert g.license_from_text("no idea") == ""


def test_parse_models_table() -> None:
    md = (
        "| Role | Model (upstream) | Weights | License | Default |\n"
        "|---|---|---|---|---|\n"
        "| Dense | [`intfloat/multilingual-e5-large`](https://huggingface.co/intfloat/"
        "multilingual-e5-large) | `qdrant/x@ac6781cd` | MIT | ✅ local |\n"
        "| Reranker, legacy | [`jinaai/jina`](https://huggingface.co/jinaai/jina) | `@9cfeff2d` "
        "| **CC-BY-NC-4.0 (non-commercial)** | opt-in only |\n"
    )
    # Only default (baked, ✅) models are distributed; opt-in rows are models an
    # operator downloads themselves, so they are not part of the notices.
    assert g.parse_models(md) == [
        g.Dep(
            "intfloat/multilingual-e5-large",
            "ac6781cd",
            "MIT",
            "https://huggingface.co/intfloat/multilingual-e5-large",
        ),
    ]


def test_parse_models_skips_opt_in_rows_and_reads_the_real_file() -> None:
    md = (
        "| Role | Model (upstream) | Weights | License | Default |\n"
        "|---|---|---|---|---|\n"
        "| Reranker, slower | [`BAAI/bge`](https://huggingface.co/BAAI/bge) | `x/y@6f5ff652` "
        "| Apache-2.0 | opt-in |\n"
    )
    assert g.parse_models(md) == []
    real = g.parse_models((Path(__file__).resolve().parents[2] / "MODELS.md").read_text("utf-8"))
    names = {d.name for d in real}
    assert "jinaai/jina-reranker-v2-base-multilingual" not in names
    assert {
        "intfloat/multilingual-e5-large",
        "Qdrant/bm25",
        "Alibaba-NLP/gte-multilingual-reranker-base",
    } <= names


def test_render_flags_review_items_first() -> None:
    comps = [
        g.Component(
            "web (npm, production)",
            [
                g.Dep("react", "19.0.0", "MIT", "https://react.dev"),
                g.Dep("@img/sharp-libvips-linux-x64", "1.2.0", "LGPL-3.0-or-later", "https://n/x"),
            ],
        ),
        g.Component("Python — services/workers", [g.Dep("weird", "1.0", "", "https://p/w")]),
    ]
    md = g.render(comps)
    review = md.index("## Review required")
    assert review < md.index("## web (npm, production)")
    head = md[review : md.index("## web (npm, production)")]
    assert "@img/sharp-libvips-linux-x64" in head and "weak copyleft" in head
    assert "weird" in head and "unknown" in head
    assert "react" not in head
    assert "| react | 19.0.0 | MIT | https://react.dev |" in md
    assert md.endswith("\n") and "do not edit" in md.lower()


def test_render_escapes_table_cells() -> None:
    md = g.render([g.Component("x", [g.Dep("a|b", "1", "MIT OR\nApache-2.0", "u")])])
    assert "| a\\|b | 1 | MIT OR Apache-2.0 | u |" in md
