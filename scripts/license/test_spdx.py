from __future__ import annotations

from pathlib import Path

import pytest
import spdx

H = "SPDX-License-Identifier: Apache-2.0"


@pytest.mark.parametrize(
    ("name", "before", "after"),
    [
        ("a.go", "package x\n", f"// {H}\n\npackage x\n"),
        # Build constraints keep working: only line comments/blank lines precede them.
        (
            "a.go",
            "//go:build linux\n\npackage x\n",
            f"// {H}\n\n//go:build linux\n\npackage x\n",
        ),
        ("a.tsx", '"use client";\nexport {};\n', f'// {H}\n\n"use client";\nexport {{}};\n'),
        ("a.mjs", "export {};\n", f"// {H}\n\nexport {{}};\n"),
        ("a.sql", "SELECT 1;\n", f"-- {H}\n\nSELECT 1;\n"),
        ("a.py", '"""Doc."""\n', f'# {H}\n\n"""Doc."""\n'),
        ("a.sql", "-- why\nSELECT 1;\n", f"-- {H}\n-- why\nSELECT 1;\n"),
        # A Go/JS comment right below would otherwise merge into the doc comment.
        (
            "a.go",
            "// Package x does y.\npackage x\n",
            f"// {H}\n\n// Package x does y.\npackage x\n",
        ),
        ("a.py", "", f"# {H}\n"),
        (
            "a.py",
            "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nx = 1\n",
            f"#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n# {H}\n\nx = 1\n",
        ),
        ("a.sh", "#!/usr/bin/env bash\nset -e\n", f"#!/usr/bin/env bash\n# {H}\n\nset -e\n"),
        ("a.sh", "#!/bin/sh\n# helper\n", f"#!/bin/sh\n# {H}\n# helper\n"),
        # Dockerfile parser directives must stay the very first lines.
        (
            "Dockerfile",
            "# syntax=docker/dockerfile:1\n\nFROM x\n",
            f"# syntax=docker/dockerfile:1\n# {H}\n\nFROM x\n",
        ),
        (
            "Dockerfile.mockllm",
            "# syntax=docker/dockerfile:1\n# mock\nFROM x\n",
            f"# syntax=docker/dockerfile:1\n# {H}\n# mock\nFROM x\n",
        ),
        ("a.ts", "export {};\r\n", f"// {H}\r\n\r\nexport {{}};\r\n"),
    ],
)
def test_adds_a_one_line_header_in_the_right_place(name, before, after) -> None:
    assert spdx.with_header(Path(name), before) == after


@pytest.mark.parametrize(
    "text",
    [
        f"// {H}\npackage x\n",
        f"#!/bin/sh\n# {H}\n",
        "// Code generated by sqlc. DO NOT EDIT.\npackage db\n",
        "/** @generated */\nexport {};\n",
    ],
)
def test_leaves_headed_and_generated_files_alone(text) -> None:
    assert spdx.with_header(Path("f.go"), text) is None


def test_header_is_idempotent() -> None:
    once = spdx.with_header(Path("a.py"), "x = 1\n")
    assert once is not None and spdx.with_header(Path("a.py"), once) is None


@pytest.mark.parametrize(
    ("path", "selected"),
    [
        ("services/edge/main.go", True),
        ("services/edge/Dockerfile.mockllm", True),
        ("web/app/page.tsx", True),
        ("services/control-plane/migrations/0001_initial_schema.up.sql", True),
        ("web/next-env.d.ts", False),
        ("web/node_modules/x/index.js", False),
        ("web/.next/server/app.js", False),
        ("examples/sample-corpus/x.py", False),
        ("docs/snippet.sh", False),
        ("services/edge/internal/x/testdata/fuzz/FuzzX/abc", False),
        ("services/edge/internal/x/testdata/case.go", False),
        ("README.md", False),
        ("web/package.json", False),
    ],
)
def test_selects_first_party_sources_only(path, selected) -> None:
    assert spdx.is_target(path) is selected


def test_check_mode_reports_missing_and_fix_mode_repairs(tmp_path) -> None:
    good = tmp_path / "good.py"
    good.write_text(f"# {H}\n", encoding="utf-8")
    bad = tmp_path / "bad.go"
    bad.write_text("package x\n", encoding="utf-8")

    assert spdx.run([good, bad], fix=False) == [bad]
    assert bad.read_text(encoding="utf-8") == "package x\n"  # check never writes
    assert spdx.run([good, bad], fix=True) == [bad]
    assert spdx.run([good, bad], fix=False) == []
